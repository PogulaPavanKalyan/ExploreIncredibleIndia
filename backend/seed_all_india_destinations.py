def seed_all_india_master():
    print("=== SEEDING ALL-INDIA MASTER DESTINATION ATLAS ===")
    created = 0
    updated = 0

    for d in MASTER_DESTINATIONS:
        state_obj, _ = State.objects.get_or_create(
            name=d["state_name"],
            defaults={"slug": d["state_name"].lower().replace(' ', '-')}
        )

        dest, was_created = Destination.objects.update_or_create(
            slug=d["slug"],
            defaults={
                "name": d["name"],
                "state": state_obj,
                "district": d.get("district", ""),
                "region": d.get("region", "south-india"),
                "pilgrimage_collection": d.get("pilgrimage_collection", "none"),
                "temple_deity": d.get("temple_deity", ""),
                "spiritual_tradition": d.get("spiritual_tradition", ""),
                "temple_architecture": d.get("temple_architecture", ""),
                "famous_for": d.get("famous_for", ""),
                "short_description": d["short_description"],
                "description": d["description"],
                "things_to_do": d.get("things_to_do", ""),
                "best_time_to_visit": d.get("best_time_to_visit", "October to March"),
                "opening_time": d.get("opening_time", "06:00 AM"),
                "closing_time": d.get("closing_time", "09:00 PM"),
                "ticket_price": Decimal(str(d.get("ticket_price", 0.0))),
                "recommended_duration": d.get("recommended_duration", "2-3 Hours"),
                "nearest_airport": d.get("nearest_airport", ""),
                "nearest_railway": d.get("nearest_railway", ""),
                "nearest_bus_station": d.get("nearest_bus_station", ""),
                "safety_info": d.get("safety_info", "Safe for solo and family travelers."),
                "weather_info": d.get("weather_info", "Pleasant throughout winter."),
                "latitude": d.get("latitude", Decimal("20.5937")),
                "longitude": d.get("longitude", Decimal("78.9629")),
                "featured": d.get("featured", False),
                "trending": d.get("trending", False),
                "published": True,
                "verification_status": "verified",
                "data_completeness_score": 95,
                "popularity_score": d.get("popularity_score", 90),
                "source_name": "Ministry of Tourism & State Tourism Boards",
                "main_image": d["main_image"],
            }
        )

        if d.get("history"):
            from apps.destinations.models import DestinationHistory
            DestinationHistory.objects.update_or_create(
                destination=dest,
                defaults={
                    "short_history": d["history"],
                    "detailed_history": d["history"],
                    "architecture": d.get("temple_architecture", "Ancient Heritage"),
                    "religious_significance": d.get("spiritual_tradition", "")
                }
            )

        # Attach categories
        for cat_name in d.get("categories", ["Nature"]):
            cat_obj, _ = Category.objects.get_or_create(
                name=cat_name,
                defaults={"slug": cat_name.lower().replace(' ', '-')}
            )
            dest.categories.add(cat_obj)

        if was_created:
            created += 1
            print(f" [+] Created: {dest.name} ({dest.state.name}) - Collection: {dest.pilgrimage_collection}")
        else:
            updated += 1
            print(f" [~] Updated: {dest.name} ({dest.state.name}) - Collection: {dest.pilgrimage_collection}")

    print(f"\nAll-India Master Seeding Complete: {created} created, {updated} updated. Total in DB: {Destination.objects.count()}")

if __name__ == '__main__':
    seed_all_india_master()
